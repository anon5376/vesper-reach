export function labelFor(code) {
  if (!code) return '—'
  const named = {
    Space: 'Space',
    ShiftLeft: 'Shift',
    ShiftRight: 'RShift',
    ControlLeft: 'Ctrl',
    ControlRight: 'RCtrl',
    AltLeft: 'Alt',
    Tab: 'Tab',
    Enter: 'Enter',
    Escape: 'Esc',
    Backspace: 'Bksp',
    Minus: '-',
    Equal: '=',
    Mouse0: 'LMB',
    Mouse1: 'MMB',
    Mouse2: 'RMB',
  }
  if (named[code]) return named[code]
  if (code.startsWith('Key')) return code.slice(3)
  if (code.startsWith('Digit')) return code.slice(5)
  if (code.startsWith('Arrow')) return code.slice(5)
  return code
}
